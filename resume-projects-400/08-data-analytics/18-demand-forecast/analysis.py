#!/usr/bin/env python3
from __future__ import annotations
import json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parents[1]))
from analytics_core import *

def analyze(rows):
    values=[f(r,"demand") for r in rows];forecast=round2(mean(values[-3:]));trend=round2(values[-1]-values[-2]);series={r["month"]:f(r,"demand") for r in rows};series["Next forecast"]=forecast;return result({"three_period_forecast":forecast,"latest_change":trend,"method":"simple moving average"},"Demand and next forecast",series)

def main():
 root=Path(__file__).parent
 with (root/"data.csv").open(newline="",encoding="utf-8") as handle:rows=list(csv.DictReader(handle))
 output=analyze(rows);(root/"output").mkdir(exist_ok=True)
 (root/"output"/"summary.json").write_text(json.dumps(output["summary"],indent=2)+"\n")
 (root/"output"/"chart.svg").write_text(svg_bar(output["chart"]["title"],output["chart"]["data"]))
 print(json.dumps(output["summary"],indent=2))
if __name__=="__main__":main()
